# ---------------- e-mail ----------------
def money(v, ccy):
    return '%s %s' % (ccy, '{:,.2f}'.format(v or 0))


def kpi_email(company, k, period_note):
    ccy = k['currency']
    rows = [('Contracts', k['k03']), ('Original contract value', money(k['k04'], ccy)), ('Revised contract value (approved variations only)', money(k['k05'], ccy)),
            ('Approved variations', money(k['k10'], ccy)), ('Pending variations – not contract value', money(k['k11'], ccy)), ('Claims submitted', k['k12']),
            ('Certified (net payable)', money(k['certified'], ccy)), ('Paid', money(k['paid'], ccy)), ('Outstanding payments', money(k['k13'], ccy)),
            ('Retention held', money(k['k14'], ccy))]
    html = ('<div style="font-family:Arial,sans-serif;color:#16202b"><h2 style="margin:0 0 4px">%s – commercial summary</h2><p style="color:#5b6674;margin:0 0 12px">%s</p>'
            '<table style="border-collapse:collapse">%s</table>%s<p style="color:#5b6674;font-size:12px">Generated by Contract Assessment Tools from the live register. '
            'Exposure figures are estimates, not liabilities. Draft information – not approved for issue.</p></div>') % (
        escape(company.get('name', '')), escape(period_note),
        ''.join('<tr><td style="padding:4px 12px 4px 0;border-bottom:1px solid #dde2e8">%s</td><td style="padding:4px 0;border-bottom:1px solid #dde2e8;text-align:right;font-family:monospace">%s</td></tr>' % (escape(a), escape(str(b))) for a, b in rows),
        ('<p style="color:#b42318">Excluded from money figures (no approved exchange rate): %s</p>' % escape(', '.join(k['excluded']))) if k['excluded'] else '')
    text = '\n'.join('%s: %s' % r for r in rows)
    return html, text


def send_mail(to, subject, html, text):
    if not config.SMTP_HOST:
        raise RuntimeError('SMTP is not configured (SMTP_HOST)')
    m = EmailMessage(); m['From'] = config.SMTP_FROM; m['To'] = ', '.join(to); m['Subject'] = subject
    m.set_content(text); m.add_alternative(html, subtype='html')
    with smtplib.SMTP(config.SMTP_HOST, config.SMTP_PORT, timeout=30) as s:
        if config.SMTP_TLS:
            s.starttls()
        if config.SMTP_USER:
            s.login(config.SMTP_USER, config.SMTP_PASSWORD)
        s.send_message(m)


def due(sch, t):
    """Is schedule `sch` due at UTC time t (checked once a minute)?"""
    if not sch.active:
        return False
    last = sch.last_run.replace(tzinfo=dt.timezone.utc) if sch.last_run and not sch.last_run.tzinfo else sch.last_run
    if t.hour != (sch.hour or 0):
        return False
    if sch.frequency == 'weekly' and t.weekday() != (sch.weekday or 0):
        return False
    if sch.frequency == 'monthly' and t.day != (sch.monthday or 1):
        return False
    return not last or last.date() < t.date()


def run_schedule(sch, company_rows, actor='scheduler'):
    with st.engine.begin() as c:
        rows, comp = company_rows(c, sch.company_id)
    k = L.kpis(rows, comp)
    html, text = kpi_email(comp, k, 'All recorded activity to %s (UTC)' % st.now().strftime('%d %b %Y %H:%M'))
    to = [x.strip() for x in (sch.recipients or '').replace(';', ',').split(',') if x.strip()]
    try:
        send_mail(to, '%s – %s' % (sch.name or 'Commercial summary', comp.get('name', '')), html, text)
        status = 'Sent to %d recipient(s)' % len(to)
    except Exception as e:
        status = 'Not sent: %s' % e
    with st.engine.begin() as c:
        c.execute(update(st.schedules).where(st.schedules.c.id == sch.id).values(last_run=st.now(), last_status=status))
        st.write_audit(c, sch.company_id, {'name': actor}, 'Scheduled e-mail', 'schedules', (sch.name or '') + ': ' + status)
    return status


# ---------------- backups ----------------
def _ser(v):
    return v.isoformat() if isinstance(v, (dt.datetime, dt.date)) else v


def export_all():
    out = {'app': config.APP_VERSION, 'schema': st.SCHEMA_VERSION, 'db': st.engine.dialect.name, 'created': st.now().isoformat(), 'tables': {}}
    with st.engine.begin() as c:
        for t in TABLES:
            out['tables'][t.name] = [{k: _ser(v) for k, v in r._mapping.items()} for r in c.execute(select(t))]
    return out


def import_all(dump):
    if dump.get('schema') != st.SCHEMA_VERSION:
        raise ValueError('Backup schema %s does not match server schema %s' % (dump.get('schema'), st.SCHEMA_VERSION))
    with st.engine.begin() as c:
        for t in reversed(TABLES):
            c.execute(delete(t))
        for t in TABLES:
            rows = dump['tables'].get(t.name, [])
            for r in rows:
                for col in t.columns:
                    if isinstance(col.type, st.DateTime) and r.get(col.name):
                        r[col.name] = dt.datetime.fromisoformat(r[col.name])
            if rows:
                c.execute(insert(t), rows)
        if st.IS_PG:
            for t in (st.record_history, st.audit_log, st.ai_usage):
                pk = list(t.primary_key.columns)[0].name
                c.exec_driver_sql("SELECT setval(pg_get_serial_sequence('%s','%s'), COALESCE((SELECT MAX(%s) FROM %s),0)+1, false)" % (t.name, pk, pk, t.name))


def write_backup(label='nightly'):
    d = export_all(); name = 'cat-%s-%s.json.gz' % (st.now().strftime('%Y%m%d-%H%M%S'), label)
    p = config.BACKUP_DIR / name
    p.write_bytes(gzip.compress(json.dumps(d).encode()))
    backups = sorted(config.BACKUP_DIR.glob('cat-*.json.gz'))
    for old in backups[:-config.BACKUP_KEEP]:
        old.unlink()
    return p


def verify_backup(p):
    d = json.loads(gzip.decompress(p.read_bytes()))
    n = sum(len(v) for v in d['tables'].values())
    return {'file': p.name, 'rows': n, 'records': len(d['tables'].get('records', [])), 'schema': d.get('schema')}


# ---------------- scheduler thread ----------------
_started = False


def start(company_rows):
    global _started
    if _started or not config.RUN_JOBS:
        return
    _started = True

    def loop():
        last_backup = None
        while True:
            try:
                t = st.now()
                with st.engine.begin() as c:
                    schs = list(c.execute(select(st.schedules)))
                    c.execute(delete(st.req_metrics).where(st.req_metrics.c.at < t - dt.timedelta(days=7)))
                    c.execute(delete(st.sessions).where(st.sessions.c.expires < t))
                for s in schs:
                    if due(s, t):
                        run_schedule(s, company_rows)
                if t.hour == config.BACKUP_HOUR and last_backup != t.date():
                    p = write_backup(); last_backup = t.date()
                    with st.engine.begin() as c:
                        st.write_audit(c, None, {'name': 'scheduler'}, 'Nightly backup', 'system', p.name)
            except Exception as e:  # keep the loop alive
                print('job loop error', e)
            time.sleep(60)
    threading.Thread(target=loop, daemon=True, name='cat-jobs').start()


# ---------------- routes ----------------
class Sched(BaseModel):
    name: str
    recipients: str
    frequency: str = 'weekly'
    hour: int = 6
    weekday: int = 0
    monthday: int = 1
    active: bool = True
    companyId: Optional[str] = None


def register(app, current_user, ip_of, company_rows):
    def admin(u):
        if not L.role_of(u).get('admin'):
            raise HTTPException(403, 'Administrators only')

    def cid_for(u, cid):
        return cid if (cid and L.is_super(u)) else u.get('companyId')

    @app.get('/api/schedules')
    def list_sched(companyId: Optional[str] = None, u=Depends(current_user)):
        with st.engine.begin() as c:
            rows = c.execute(select(st.schedules).where(st.schedules.c.company_id == cid_for(u, companyId)))
            return [{k: _ser(v) for k, v in r._mapping.items()} for r in rows]

    @app.post('/api/schedules')
    def add_sched(b: Sched, request: Request, u=Depends(current_user)):
        admin(u)
        if b.frequency not in ('daily', 'weekly', 'monthly') or not (0 <= b.hour <= 23) or not (0 <= b.weekday <= 6) or not (1 <= b.monthday <= 28):
            raise HTTPException(400, 'Frequency must be daily, weekly or monthly; hour 0–23 (UTC); weekday 0–6; day of month 1–28.')
        to = [x.strip() for x in b.recipients.replace(';', ',').split(',') if x.strip()]
        if not to or any('@' not in x for x in to):
            raise HTTPException(400, 'Give one or more valid e-mail recipients.')
        sid = 'sch_' + secrets.token_hex(6)
        with st.engine.begin() as c:
            c.execute(insert(st.schedules).values(id=sid, company_id=cid_for(u, b.companyId), name=b.name[:200], recipients=', '.join(to), frequency=b.frequency,
                                                  hour=b.hour, weekday=b.weekday, monthday=b.monthday, active=b.active, created_by=u.get('name')))
            st.write_audit(c, cid_for(u, b.companyId), u, 'Created', 'schedules', b.name, ip_of(request))
        return {'id': sid}

    @app.delete('/api/schedules/{sid}')
    def del_sched(sid: str, request: Request, u=Depends(current_user)):
        admin(u)
        with st.engine.begin() as c:
            s = c.execute(select(st.schedules).where(st.schedules.c.id == sid)).first()
            if not s or (not L.is_super(u) and s.company_id != u.get('companyId')):
                raise HTTPException(404, 'Not found')
            c.execute(delete(st.schedules).where(st.schedules.c.id == sid))
            st.write_audit(c, s.company_id, u, 'Deleted', 'schedules', s.name, ip_of(request))
        return {'ok': True}

    @app.post('/api/schedules/{sid}/run')
    def run_now(sid: str, u=Depends(current_user)):
        admin(u)
        with st.engine.begin() as c:
            s = c.execute(select(st.schedules).where(st.schedules.c.id == sid)).first()
        if not s or (not L.is_super(u) and s.company_id != u.get('companyId')):
            raise HTTPException(404, 'Not found')
        return {'status': run_schedule(s, company_rows, actor=u.get('name'))}

    @app.get('/api/admin/backup')
    def backup(request: Request, u=Depends(current_user)):
        if not L.is_super(u):
            raise HTTPException(403, 'Super Administrator only')
        body = gzip.compress(json.dumps(export_all()).encode())
        with st.engine.begin() as c:
            st.write_audit(c, None, u, 'Downloaded server backup', 'system', '%d bytes' % len(body), ip_of(request))
        return Response(body, media_type='application/gzip', headers={'Content-Disposition': 'attachment; filename="cat-server-backup-%s.json.gz"' % st.now().strftime('%Y%m%d-%H%M')})

    @app.post('/api/admin/backup/now')
    def backup_now(u=Depends(current_user)):
        if not L.is_super(u):
            raise HTTPException(403, 'Super Administrator only')
        p = write_backup('manual')
        return verify_backup(p)

    @app.get('/api/admin/backups')
    def backups(u=Depends(current_user)):
        if not L.is_super(u):
            raise HTTPException(403, 'Super Administrator only')
        return [{'file': p.name, 'bytes': p.stat().st_size} for p in sorted(config.BACKUP_DIR.glob('cat-*.json.gz'), reverse=True)]

    @app.post('/api/admin/restore')
    async def restore(request: Request, file: UploadFile = File(...), u=Depends(current_user)):
        if not L.is_super(u):
            raise HTTPException(403, 'Super Administrator only')
        raw = await file.read()
        try:
            dump = json.loads(gzip.decompress(raw) if raw[:2] == b'\x1f\x8b' else raw)
        except Exception:
            raise HTTPException(400, 'Not a server backup file')
        safety = write_backup('before-restore')
        try:
            import_all(dump)
        except Exception as e:
            raise HTTPException(400, 'Restore failed and nothing was changed: %s' % e)
        with st.engine.begin() as c:
            st.write_audit(c, None, u, 'Restored server backup', 'system', 'from %s; safety copy %s' % (dump.get('created'), safety.name), ip_of(request))
            chain = st.verify_audit_chain(c)
        return {'ok': True, 'safety': safety.name, 'audit': chain}

    @app.get('/api/admin/status')
    def status(u=Depends(current_user)):
        admin(u)
        with st.engine.begin() as c:
            t = st.now()
            q = select(func.count(), func.avg(st.req_metrics.c.ms), func.max(st.req_metrics.c.ms)).where(st.req_metrics.c.at > t - dt.timedelta(hours=24))
            n, avg, mx = c.execute(q).first()
            errs = c.execute(select(func.count()).select_from(st.req_metrics).where(st.req_metrics.c.at > t - dt.timedelta(hours=24), st.req_metrics.c.status >= 500)).scalar()
            recs = c.execute(select(func.count()).select_from(st.records).where(st.records.c.removed == False)).scalar()  # noqa: E712
            sess = c.execute(select(func.count()).select_from(st.sessions).where(st.sessions.c.expires > t)).scalar()
            chain = st.verify_audit_chain(c)
        bk = sorted(config.BACKUP_DIR.glob('cat-*.json.gz'), reverse=True)
        return {'requests24h': n, 'avgMs': round(avg or 0, 1), 'maxMs': round(mx or 0, 1), 'errors24h': errs, 'records': recs, 'activeSessions': sess,
                'auditChain': chain, 'lastBackup': bk[0].name if bk else None, 'backups': len(bk), 'db': st.engine.dialect.name,
                'smtp': bool(config.SMTP_HOST), 'ai': bool(config.ANTHROPIC_API_KEY), 'version': config.APP_VERSION}

    start(company_rows)
